/// UWAGA dot. zdjęć: EGGER przechowuje miniatury dekorów pod losowymi
/// identyfikatorami CDN, których nie da się wyliczyć z samego kodu.
/// Zamiast pobierać każde zdjęcie osobno (setki zapytań), [officialUrl]
/// generuje link do oficjalnej strony dekoru na egger.com, gdzie zdjęcie
/// jest dostępne od ręki. Jeśli potrzebne są realne miniatury zapisane
/// offline w aplikacji — dla wybranej, krótszej listy dekorów faktycznie
/// używanych w magazynie da się je pobrać i wbudować w kolejnej wersji.
class EggerColour {
  final String code; // np. U702
  final String texture; // np. ST9, PM, PG, PT, SM, A
  final String name; // np. Cashmere Grey

  const EggerColour(this.code, this.texture, this.name);

  String get fullCode => '$code $texture';

  /// Link do oficjalnej strony dekoru z możliwością obejrzenia zdjęcia.
  /// Wzór zaobserwowany na egger.com: /decors/{CODE}_{NUMER_TEKSTURY}
  /// (dla ST-tekstur bierzemy same cyfry, dla PM/PT/PG/SM/A - kod tekstury wprost).
  String get officialUrl {
    final textureSlug = texture.startsWith('ST')
        ? texture.substring(2)
        : texture;
    return 'https://www.egger.com/en/furniture-and-interior-design/decors/${code}_$textureSlug';
  }

  @override
  String toString() => '$fullCode — $name';
}

