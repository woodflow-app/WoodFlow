/// Wyszukiwanie po kodzie lub nazwie (do autouzupełniania w formularzu).
List<EggerColour> searchEggerColours(String query) {
  if (query.trim().isEmpty) return eggerColours;
  final q = query.toLowerCase();
  return eggerColours
      .where((c) =>
          c.fullCode.toLowerCase().contains(q) ||
          c.name.toLowerCase().contains(q))
      .toList();
}
